// npm run export:osm [dataDir]
// Checklist of verified shortcuts (and indoor-override doors) that OSM does not have yet, for adding by hand in iD.
// Writes docs/v2/osm-checklist.md and data/raw/reports/osm-checklist.html. Never uploads anything.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import type { Evidence, LatLon } from '../../src/domain/schemas.ts'
import { readEvidence } from './store.ts'

export interface ChecklistRow {
  id: string
  area: string
  kind: string
  label: string
  at: LatLon
  editUrl: string
  tags: string
  imagery: string
}

interface Feat { properties: Record<string, unknown>; geometry: { type: string; coordinates: unknown } }

const TAGS: Record<string, string> = {
  footpath: 'highway=footway',
  'covered-walkway': 'highway=footway, covered=yes',
  stairs: 'highway=steps',
  'through-building': 'highway=footway, tunnel=building_passage, covered=yes',
  bridge: 'highway=footway, bridge=yes, layer=1',
  door: 'entrance=yes (add door=* and name/ref if known)',
}

const editUrl = (p: LatLon) => `https://www.openstreetmap.org/edit?editor=id#map=20/${p.lat.toFixed(6)}/${p.lon.toFixed(6)}`

function midpoint(line: LatLon[]): LatLon {
  const seg = line.slice(1).map((p, i) => Math.hypot(p.lat - line[i].lat, (p.lon - line[i].lon) * Math.cos((p.lat * Math.PI) / 180)))
  let left = seg.reduce((s, x) => s + x, 0) / 2
  for (let i = 0; i < seg.length; i++) {
    if (left <= seg[i] || i === seg.length - 1) {
      const t = seg[i] === 0 ? 0 : Math.min(1, left / seg[i])
      return { lat: line[i].lat + (line[i + 1].lat - line[i].lat) * t, lon: line[i].lon + (line[i + 1].lon - line[i].lon) * t }
    }
    left -= seg[i]
  }
  return line[0]
}

function nearestLandmark(p: LatLon, landmarks: [number, number, string][]): string {
  let best = 'Unnamed area'
  let d = Infinity
  for (const [lat, lon, name] of landmarks) {
    const x = Math.hypot(lat - p.lat, (lon - p.lon) * Math.cos((p.lat * Math.PI) / 180))
    if (x < d) { d = x; best = name }
  }
  return best
}

/** Imagery of the satellite evidence for this id, else either. */
function imageryFor(id: string, evidence: Evidence[]): string {
  const set = new Set(evidence.filter((e) => e.shortcutId === id && e.imagery).map((e) => e.imagery!))
  const names = [...set].map((s) => (s === 'esri' ? 'Esri World Imagery' : 'Bing Aerial'))
  return names.length ? names.join(' + ') : 'Esri World Imagery or Bing Aerial'
}

/** Verified, public, not-yet-in-OSM scored shortcuts plus door points, sorted by area then id. */
export function checklistRows(scored: Feat[], doors: Feat[], evidence: Evidence[], landmarks: [number, number, string][]): ChecklistRow[] {
  const rows: ChecklistRow[] = []
  for (const f of scored) {
    const p = f.properties
    if (p.level !== 'verified' || p.inOsm || p.access === 'private' || f.geometry.type !== 'LineString') continue
    const line = (f.geometry.coordinates as [number, number][]).map(([lon, lat]) => ({ lat, lon }))
    const at = midpoint(line)
    const kind = String(p.kind ?? 'footpath')
    rows.push({
      id: String(p.id),
      area: nearestLandmark(at, landmarks),
      kind,
      label: `${p.from ?? '?'} to ${p.to ?? '?'}`,
      at,
      editUrl: editUrl(at),
      tags: TAGS[kind] ?? TAGS.footpath,
      imagery: imageryFor(String(p.id), evidence),
    })
  }
  for (const f of doors) {
    if (f.geometry.type !== 'Point') continue
    const [lon, lat] = f.geometry.coordinates as [number, number]
    const at = { lat, lon }
    rows.push({ id: `door-${lat.toFixed(5)}-${lon.toFixed(5)}`, area: nearestLandmark(at, landmarks), kind: 'door', label: String(f.properties.name ?? 'door'), at, editUrl: editUrl(at), tags: TAGS.door, imagery: 'Esri World Imagery or Bing Aerial' })
  }
  return rows.sort((a, b) => a.area.localeCompare(b.area) || a.id.localeCompare(b.id))
}

const esc = (s: string) => s.replace(/[&<>|]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '|': '\\|' })[c]!)
function byArea(rows: ChecklistRow[]): [string, ChecklistRow[]][] {
  const m = new Map<string, ChecklistRow[]>()
  for (const r of rows) m.set(r.area, [...(m.get(r.area) ?? []), r])
  return [...m]
}
const EMPTY = 'Nothing to add: no verified shortcut is missing from OSM right now.'

export function renderMarkdown(rows: ChecklistRow[]): string {
  const head = `# OSM checklist

Verified shortcuts and doors that OpenStreetMap does not have yet. Add them by hand in the iD editor, one small changeset per area. No bulk uploads. Check the line against the imagery named in the row before drawing it, and do not copy from Google. Generated by \`npm run export:osm\`; do not edit by hand.

`
  if (!rows.length) return `${head}${EMPTY}\n`
  return head + byArea(rows).map(([area, rs]) => `## ${area} (${rs.length})\n\n| Done | Item | Kind | Suggested tags | Imagery | iD |\n|---|---|---|---|---|---|\n${rs.map((r) => `| [ ] | \`${r.id}\` ${esc(r.label)} | ${r.kind} | \`${r.tags}\` | ${r.imagery} | [open](${r.editUrl}) |`).join('\n')}\n`).join('\n')
}

export function renderHtml(rows: ChecklistRow[]): string {
  const body = rows.length
    ? byArea(rows).map(([area, rs]) => `<h2>${esc(area)} (${rs.length})</h2><table><tr><th>Item</th><th>Kind</th><th>Suggested tags</th><th>Imagery</th><th>iD</th></tr>${rs.map((r) => `<tr><td><code>${r.id}</code> ${esc(r.label)}</td><td>${r.kind}</td><td><code>${esc(r.tags)}</code></td><td>${r.imagery}</td><td><a href="${r.editUrl}">open</a></td></tr>`).join('')}</table>`).join('')
    : `<p>${EMPTY}</p>`
  return `<!doctype html><meta charset=utf-8><title>OSM checklist</title><style>body{font:14px system-ui;margin:20px}table{border-collapse:collapse}td,th{border:1px solid #ccc;padding:3px 8px;text-align:left}</style><h1>OSM checklist</h1>${body}\n`
}

function readFeatures(path: string): Feat[] {
  return existsSync(path) ? (JSON.parse(readFileSync(path, 'utf8')) as { features: Feat[] }).features : []
}

if (process.argv[1]?.endsWith('osm-export.ts')) {
  const root = process.argv[2] ?? 'data'
  const indoor = join(root, 'overrides', 'indoor')
  const doors = existsSync(indoor) ? readdirSync(indoor).filter((n) => n.endsWith('.geojson')).flatMap((n) => readFeatures(join(indoor, n))) : []
  const landmarks = JSON.parse(readFileSync(join(root, 'osm', 'landmarks.json'), 'utf8'))
  const rows = checklistRows(readFeatures(join(root, 'shortcuts', 'scored.geojson')), doors, readEvidence(root), landmarks)
  mkdirSync('docs/v2', { recursive: true })
  mkdirSync(join(root, 'raw', 'reports'), { recursive: true })
  writeFileSync('docs/v2/osm-checklist.md', renderMarkdown(rows))
  writeFileSync(join(root, 'raw', 'reports', 'osm-checklist.html'), renderHtml(rows))
  console.log(`${rows.length} items in ${new Set(rows.map((r) => r.area)).size} areas -> docs/v2/osm-checklist.md`)
}
